#!/usr/bin/env python3
"""Generate FIELD-CATALOG.md and EVENT-CATALOG.md from the imported Causa v1.0.0 JSON Schemas.

Usage:
  python3 -I tools/causa-contract/generate_catalogs.py write  [contractDir]
  python3 -I tools/causa-contract/generate_catalogs.py check  [contractDir] [--dataset <causa-data checkout>]

`check` fails (exit 1) when a committed catalog differs from regeneration, when any schema property has no semantic
entry, or (with --dataset) when any JSON path that occurs in the frozen dataset is not documented in the catalog.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from typing import Any, Iterable, Mapping

sys.path.insert(0, str(Path(__file__).resolve().parent))

import contract_model as cm  # noqa: E402

DEFAULT_ROOT = Path(__file__).resolve().parents[2] / "requirements" / "causa" / "data" / "v1.0.0"
GENERATED = "<!-- GENERATED by tools/causa-contract/generate_catalogs.py from schemas/ and catalog/*.json. Do not edit by hand. -->"


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ") if text else ""


def allowed_text(f: cm.Field) -> str:
    return ", ".join(f"`{v}`" for v in f.allowed)


def validation_rule(f: cm.Field, sem: cm.Semantic) -> str:
    parts = (
        "key MUST be present" if f.required else "key optional",
        "value MAY be null" if f.nullable else "MUST NOT be null",
        f"one of {allowed_text(f)}" if f.allowed and len(f.allowed) <= 12 else "",
        *f.conditions,
        sem.rule,
    )
    return "; ".join(p for p in parts if p)


def default_text(f: cm.Field, sem: cm.Semantic) -> str:
    base = "No default: key always written" + ("; `null` encodes absence (F# `None`)" if f.nullable else "")
    return f"{base}. {sem.default}" if sem.default else base + "."


def field_row(contract: cm.Contract, f: cm.Field, version: str) -> str:
    sem = cm.semantic_for(contract, f)
    assert sem is not None, f.sem_key
    cols = (
        f"`{f.path}`" + (f" ({f.variant})" if f.variant else ""),
        f"`{f.name}`",
        f.json_type,
        sem.fsharp,
        "required" if f.required else "optional",
        "yes" if f.nullable else "no",
        allowed_text(f),
        f.fmt,
        f.bounds,
        sem.meaning,
        validation_rule(f, sem),
        default_text(f, sem),
        version,
    )
    return "| " + " | ".join(cell(c) for c in cols) + " |"


HEADER = (
    "| JSON path | Field | JSON type | F# type | Required | Nullable | Allowed values | Format / pattern | Min / max "
    "| Semantic meaning | Validation rule | Default behaviour | Introduced |\n"
    "|---|---|---|---|---|---|---|---|---|---|---|---|---|"
)


def field_catalog(contract: cm.Contract) -> str:
    fields = cm.all_fields(contract)
    version = "1.0.0"
    docs = tuple(dict.fromkeys(f.document for f in fields))
    definition_keys = sorted({(f.schema, f.sem_key) for f in fields})
    bundle = cm.sha256(contract.bundle_bytes)
    sections = "\n\n".join(
        f"### {doc}\n\nSchema: `schemas/{next(f.schema for f in fields if f.document == doc)}`\n\n{HEADER}\n"
        + "\n".join(field_row(contract, f, version) for f in fields if f.document == doc)
        for doc in docs
    )
    enums = "\n".join(
        f"| `{name}` | {', '.join(f'`{v}`' for v in node['enum'])} |"
        for name, node in contract.schemas[cm.COMMON]["$defs"].items()
        if "enum" in node
    )
    return f"""# Causa v1.0.0 field catalog

{GENERATED}

Normative. Generated from the imported schemas (schema identity `{bundle}`), FIELD-MAPPING.md (payload meanings and F#
types) and `catalog/field-semantics.json` (all other meanings). Every property of every schema appears below in every
persisted document that can contain it: reusable definitions (`actor`, `provenance`, entity schemas, `causal-member`,
`hypothesis-change`) are expanded in place, never summarized. Generation fails if any property has no semantic entry.

* Documents: {len(docs)} (event envelope, {len(cm.event_types(contract))} event payloads, manifest, snapshot, golden state, root fixture manifest, golden scenario summary, negative fixture, schema bundle).
* Expanded field rows (document, path, variant): **{len(fields)}**.
* Distinct schema property definitions: **{len(definition_keys)}**.
* Every field was introduced in contract version 1.0.0. v1.0.0 has no optional keys: "Required" is `required` everywhere.

Conventions that apply to every row (CONTRACT.md §2): UTF-8 without BOM, LF only, RFC 8785 canonical bytes, closed
objects (`additionalProperties: false`, unknown keys rejected), integers only in `[-(2^53-1), 2^53-1]`, no `-0`, no
floats, nesting depth ≤ 128, unique case-sensitive keys, U+FEFF forbidden, lone surrogates forbidden, regular
expressions with ECMA-262 semantics (`$` never matches before a trailing LF). Identifier arrays keep citation order and
are never sorted; snapshot entity arrays are sorted by `id` (ordinal). Text is stored verbatim (no trim, no NFC).

## Closed enumerations

| enumeration | wire values |
|---|---|
{enums}

## Fields by document

{sections}
"""


# ------------------------------------------------------------------------------------------------- events


def projection_rows(contract_md: str) -> Mapping[str, str]:
    return {
        m.group(1): m.group(2).strip()
        for m in re.finditer(r"^\| `([A-Za-z]+)` \| (.+) \|\s*$", contract_md, flags=re.M)
        if m.group(1)[0].isupper()
    }


def event_section(contract: cm.Contract, name: str, index: int, sem: Mapping[str, Any], projection: Mapping[str, str]) -> str:
    file = f"payloads/{name}.schema.json"
    schema = contract.schemas[file]
    fields = tuple(f for f in cm.expand(contract, name, file, schema, "$.payload", file))
    rows = "\n".join(
        "| " + " | ".join(
            cell(c)
            for c in (
                f"`{f.path}`",
                f.json_type,
                "yes" if f.nullable else "no",
                "; ".join(x for x in (allowed_text(f) and "one of " + allowed_text(f), f.fmt, f.bounds) if x),
                (cm.semantic_for(contract, f) or cm.Semantic("", "", "", "")).meaning,
            )
        ) + " |"
        for f in fields
    )
    conds = "\n".join(f"- {text}" for _, text in cm.conditions_of(schema)) or "- none"
    refs = "\n".join(f"- `{k}` → existing `{v}`" for k, v in sem["references"].items()) or "- none"
    inv = "\n".join(f"- {t}" for t in sem["invariants"]) or "- none beyond the common rules"
    actor = "`human`, `system` or `agent`" if name == "ProposalRecorded" else "`human` or `system` only (an `agent` actor is a schema violation, D-004)"
    first = "MUST be `aggregateVersion` 1" if name == "InvestigationStarted" else "any position after 1"
    return f"""### {index}. `{name}`

{schema.get('description', '')}

| | |
|---|---|
| Discriminator (`eventType`) | `"{name}"` (case-sensitive) |
| Payload schema | `schemas/{file}` — SHA-256 `{cm.sha256(contract.schema_bytes[file])}` |
| Creates | {sem['creates'] or '—'} |
| Updates | {sem['updates'] or '—'} |
| Permitted actor kinds | {actor} |
| Position | {first} |
| Projection effect (CONTRACT §8.3) | {cell(projection.get(name, ''))} |
| Introduced | 1.0.0 |

Payload fields (all keys required; payload object closed):

| JSON path | JSON type | Nullable | Constraint | Meaning |
|---|---|---|---|---|
{rows}

Schema-level conditional invariants:
{conds}

Reference constraints (an id that names no existing entity makes the history inadmissible):
{refs}

Semantic invariants (normative detail and rule codes in [SEMANTICS.md](SEMANTICS.md)):
{inv}
"""


def event_catalog(contract: cm.Contract) -> str:
    sem = json.loads((contract.root / "catalog" / "event-semantics.json").read_text("utf-8"))["events"]
    names = cm.event_types(contract)
    missing = [n for n in names if n not in sem]
    extra = [n for n in sem if n not in names]
    if missing or extra:
        raise SystemExit(f"event-semantics.json out of step with the schema registry: missing={missing} extra={extra}")
    projection = projection_rows((contract.root / "CONTRACT.md").read_text("utf-8"))
    envelope = cm.expand(contract, "envelope", cm.ENVELOPE, contract.schemas[cm.ENVELOPE], "$", cm.ENVELOPE)
    env_rows = "\n".join(f"| `{f.path}`{' (' + f.variant + ')' if f.variant else ''} | {f.json_type} | {cell((cm.semantic_for(contract, f) or cm.Semantic('', '', '', '')).meaning)} |" for f in envelope)
    registry = "\n".join(f"| {i} | `{n}` | `schemas/payloads/{n}.schema.json` |" for i, n in enumerate(names, 1))
    sections = "\n".join(event_section(contract, n, i, sem[n], projection) for i, n in enumerate(names, 1))
    return f"""# Causa v1.0.0 event catalog

{GENERATED}

Normative. The registry is closed: exactly these {len(names)} discriminators, in engine `EventBody` order. Any other
`eventType` string makes the whole history invalid (`CAUSA.UNKNOWN_EVENT_TYPE`, stage 6); a non-string `eventType` is
`CAUSA.SCHEMA_VIOLATION` (stage 7). Unknown events are never skipped, preserved-and-ignored, or mapped to a generic
event (INVARIANTS.md CAUSA-INV-11).

## Envelope (every line of `events.ndjson`)

| JSON path | JSON type | Meaning |
|---|---|---|
{env_rows}

Envelope rules: `eventId = UUIDv5(241fefd4-c810-5a3a-9cfa-4bbd968ae1cb, investigationId + "/" + aggregateVersion + "/" + correlationId)`
(decimal version, lowercase UUID text, UTF-8 name). Ordering is by `aggregateVersion` only (1..N, file order); clocks
never order. One command = one or more consecutive events sharing `correlationId`, `occurredAt` and `actor`; a
`correlationId` never names two non-adjacent groups. See CONTRACT.md §5 and INVARIANTS.md.

## Registry

| # | eventType | payload schema |
|---|---|---|
{registry}

## Events

{sections}"""


# ------------------------------------------------------------------------------------------------- dataset path coverage


def json_paths(value: Any, prefix: str = "$") -> Iterable[str]:
    if isinstance(value, dict):
        for k, v in value.items():
            yield f"{prefix}.{k}"
            yield from json_paths(v, f"{prefix}.{k}")
    elif isinstance(value, list):
        for v in value:
            yield from json_paths(v, f"{prefix}[]")


def dataset_documents(dataset: Path) -> Iterable[tuple[str, Any, str]]:
    fx = dataset / "fixtures" / "v1.0.0"
    golden = dataset / "contract" / "v1.0.0" / "golden"
    for inv in sorted((fx / "investigations").iterdir()):
        for line in (inv / "events.ndjson").read_text("utf-8").split("\n")[:-1]:
            event = json.loads(line)
            yield ("events.ndjson line (envelope)", {k: (v if k != "payload" else {}) for k, v in event.items()}, "$")
            yield (cm.PAYLOAD_DOC.format(event["eventType"]), event["payload"], "$.payload")
        yield ("manifest.json (investigation manifest)", json.loads((inv / "manifest.json").read_text("utf-8")), "$")
        yield ("snapshot.json", json.loads((inv / "snapshot.json").read_text("utf-8")), "$")
    for g in sorted(golden.glob("*.state.json")):
        yield ("golden/<scenarioKey>.state.json", json.loads(g.read_text("utf-8")), "$")
    yield ("golden/scenarios.json", json.loads((golden / "scenarios.json").read_text("utf-8")), "$")
    yield ("fixtures manifest.json (root fixture manifest)", json.loads((fx / "manifest.json").read_text("utf-8")), "$")
    yield ("schemas/bundle.json (schema bundle)", json.loads((dataset / "contract" / "v1.0.0" / "schemas" / "bundle.json").read_text("utf-8")), "$")
    for n in sorted((fx / "negative").glob("*.json")):
        doc = json.loads(n.read_text("utf-8"))
        files = doc.get("files")
        normalized = doc | ({"files": {"{fileName}": v for v in files.values()}} if isinstance(files, dict) and files else {})
        yield ("negative/<name>.json (negative fixture)", normalized, "$")


def undocumented_paths(contract: cm.Contract, dataset: Path) -> tuple[tuple[str, str], ...]:
    documented = {(f.document, f.path) for f in cm.all_fields(contract)}
    seen = {(doc, p) for doc, value, prefix in dataset_documents(dataset) for p in json_paths(value, prefix)}
    return tuple(sorted(x for x in seen if x not in documented))


def main(argv: list[str]) -> int:
    mode = argv[1] if len(argv) > 1 else "check"
    root = Path(argv[2]) if len(argv) > 2 and not argv[2].startswith("--") else DEFAULT_ROOT
    dataset = Path(argv[argv.index("--dataset") + 1]) if "--dataset" in argv else None
    contract = cm.load_contract(root)
    missing = cm.missing_semantics(contract, cm.all_fields(contract))
    if missing:
        print("FAIL catalog.semantics undocumented schema properties: " + ", ".join(missing))
        return 1
    outputs = {"FIELD-CATALOG.md": field_catalog(contract), "EVENT-CATALOG.md": event_catalog(contract)}
    if mode == "write":
        for name, text in outputs.items():
            (root / name).write_text(text, "utf-8")
            print(f"wrote {root / name}")
        return 0
    stale = [name for name, text in outputs.items() if not (root / name).exists() or (root / name).read_text("utf-8") != text]
    print(("FAIL" if stale else "PASS") + " catalog.fresh " + (", ".join(stale) + " differ from regeneration" if stale else "catalogs equal regeneration"))
    gaps: tuple[tuple[str, str], ...] = ()
    if dataset is not None:
        gaps = undocumented_paths(contract, dataset)
        print(("FAIL" if gaps else "PASS") + f" catalog.dataset-coverage {len(gaps)} undocumented dataset paths")
        for doc, path in gaps:
            print(f"  undocumented: {doc} {path}")
    return 1 if stale or gaps else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
